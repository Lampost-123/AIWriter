// The New look's icons: writes src/renderer/src/components/ui/phosphorShapes.ts, the two-tone (duotone) and filled
// shapes of each Phosphor icon the app uses (the Phosphor names in ICONS, components/ui/icons.tsx). Each Phosphor
// icon in @phosphor-icons/react carries all six of its weights; the app draws only these two, so keeping just them
// keeps the app small and quick to open. Run it after adding an icon to ICONS:
//
//   node build/phosphor-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const iconsFile = join(root, 'src/renderer/src/components/ui/icons.tsx')
const outFile = join(root, 'src/renderer/src/components/ui/phosphorShapes.ts')
const defs = join(root, 'node_modules/@phosphor-icons/react/dist/defs')

// The Phosphor names ICONS uses: `Name: [L.Name, 'PhosphorName'` (and `, true]` when mirrored).
const names = [...new Set([...readFileSync(iconsFile, 'utf8').matchAll(/\[L\.\w+, '(\w+)'/g)].map((m) => m[1]))].sort()
if (!names.length) throw new Error('No Phosphor names found in icons.tsx')

/** A React element tree as plain [tag, attributes, children?] lists. */
function shapes(node) {
  if (node == null || node === false) return []
  if (Array.isArray(node)) return node.flatMap(shapes)
  const { children, ...attrs } = node.props ?? {}
  if (typeof node.type !== 'string') return shapes(children) // a Fragment
  const kids = shapes(children)
  return [kids.length ? [node.type, attrs, kids] : [node.type, attrs]]
}

const out = {}
for (const name of names) {
  const mod = await import(pathToFileURL(join(defs, `${name}.es.js`)).href)
  const weights = Object.values(mod).find((v) => v instanceof Map)
  if (!weights) throw new Error(`No weights for ${name}`)
  out[name] = { duotone: shapes(weights.get('duotone')), fill: shapes(weights.get('fill')) }
}

const lines = [
  '// Generated by build/phosphor-icons.mjs from @phosphor-icons/react (MIT, phosphoricons.com). Do not edit by hand:',
  '// add the icon to ICONS in icons.tsx and run `node build/phosphor-icons.mjs`.',
  '',
  '/** One SVG element: its tag, its attributes and any children. */',
  'export type Shape = [tag: string, attrs: Record<string, string>, children?: Shape[]]',
  '',
  '/** Each Phosphor icon the app uses: its two-tone (duotone) and filled shapes, drawn in a 256 by 256 box. */',
  'export const PHOSPHOR: Record<string, { duotone: Shape[]; fill: Shape[] }> = {',
  ...names.map((n) => `  ${n}: ${JSON.stringify(out[n])},`),
  '}',
  ''
]
writeFileSync(outFile, lines.join('\n'))
console.log(`Wrote ${names.length} icons to ${outFile}`)
